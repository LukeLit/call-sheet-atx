// Writes supabase/002_seed_programs.sql from src/data/programs.json (the one source for the starter
// list), as upserts, so it can be re-run. `pnpm seed:sql`
import { readFileSync, writeFileSync } from "node:fs";

const rows = JSON.parse(readFileSync(new URL("../src/data/programs.json", import.meta.url), "utf8"));
const q = (v) => (v === null || v === undefined ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const cols = ["id", "name", "kind", "group", "summary", "who", "amount", "opens", "closes", "rolling", "timing_note", "how_to_apply", "url", "source_url", "region", "last_verified", "verified_by"];
const value = (r, c) => (c === "who" ? `${q(JSON.stringify(r.who ?? []))}::jsonb` : c === "rolling" ? String(Boolean(r.rolling)) : q(r[c]));

const out = [
  "-- Generated by scripts/seed-sql.mjs from src/data/programs.json. Do not edit by hand.",
  `insert into public.programs (${cols.map((c) => `"${c}"`).join(", ")}) values`,
  rows.map((r) => `  (${cols.map((c) => value(r, c)).join(", ")})`).join(",\n"),
  `on conflict (id) do update set ${cols.slice(1).map((c) => `"${c}" = excluded."${c}"`).join(", ")};`,
  "",
].join("\n");
writeFileSync(new URL("../supabase/002_seed_programs.sql", import.meta.url), out);
console.log(`wrote supabase/002_seed_programs.sql (${rows.length} programs)`);
